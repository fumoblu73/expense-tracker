def get_all_icons():
    """Restituisce lista di tutte le icone disponibili"""
    all_icons = []
    for category, icons in ICON_LIBRARY.items():
        for icon_class, icon_name in icons:
            all_icons.append({
                'category': category,
                'class': icon_class,
                'name': icon_name
            })
    return all_icons


def search_icons(query):
    """Cerca icone per nome o categoria"""
    query_lower = query.lower()
    results = []

    for category, icons in ICON_LIBRARY.items():
        if query_lower in category.lower():
            # Categoria match - aggiungi tutte le icone
            for icon_class, icon_name in icons:
                results.append({
                    'category': category,
                    'class': icon_class,
                    'name': icon_name
                })
        else:
            # Cerca nelle singole icone
            for icon_class, icon_name in icons:
                if query_lower in icon_name.lower() or query_lower in icon_class:
                    results.append({
                        'category': category,
                        'class': icon_class,
                        'name': icon_name
                    })

    return results


def render_icon_html(icon_class, color='#000000', size='24px'):
    """Genera HTML per visualizzare un'icona Font Awesome"""
    return f'<i class="fa-solid {icon_class}" style="color: {color}; font-size: {size};"></i>'


def get_fontawesome_cdn():
    """Restituisce il link CDN per Font Awesome"""
    return '<link rel="stylesheet" href="https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.1/css/all.min.css">'
